import 'dart:async';
import 'dart:js_interop';

import 'package:web/web.dart' as web;

import '../models/click_sound.dart';
import 'click_player.dart';

/// Metronome click for browsers, synthesised with the Web Audio API.
///
/// Compared with playing an audio file this has much lower latency and needs
/// no assets. Each click is a very short oscillator burst with a fast decay
/// that stops itself, so clicks can never overlap or loop.
///
/// Browsers only let audio start after a user gesture. [play] is first called
/// from the Start button's tap handler, and resumes the context if needed.
class WebAudioClickPlayer implements ClickPlayer {
  web.AudioContext? _context;
  ClickSound _sound = ClickSound.classic;
  double _volume = 1.0;
  bool _disposed = false;

  @override
  void Function(Object error)? onError;

  @override
  Future<void> init() async {
    _context = web.AudioContext();
  }

  @override
  Future<void> setSound(ClickSound sound) async {
    if (_disposed) return;
    _sound = sound; // Synthesised on the fly; nothing to preload.
  }

  @override
  void setVolume(double volume) {
    _volume = volume.clamp(0.0, 1.0);
  }

  /// (waveform, accent frequency, normal frequency, decay, base gain) —
  /// mirrors the timbres generated by `tool/generate_clicks.py`.
  static (String, double, double, double, double) _timbre(ClickSound sound) =>
      switch (sound) {
        ClickSound.classic => ('sine', 1600.0, 1000.0, 0.06, 0.9),
        ClickSound.woodblock => ('triangle', 1450.0, 980.0, 0.05, 0.9),
        ClickSound.digital => ('square', 1320.0, 880.0, 0.10, 0.7),
        ClickSound.soft => ('sine', 950.0, 640.0, 0.04, 0.55),
      };

  @override
  void play({required bool accent}) {
    final context = _context;
    if (context == null || _disposed) return;
    try {
      if (context.state != 'running') {
        unawaited(
          context.resume().toDart.then<void>(
            (_) {},
            onError: (Object error) => onError?.call(error),
          ),
        );
      }

      final (wave, accentFreq, freq, decay, gain) = _timbre(_sound);
      final peak = gain * (accent ? 1.0 : 0.8) * _volume;
      if (peak <= 0) return; // Muted: an exponential ramp from 0 is invalid.
      final now = context.currentTime;
      final oscillator = context.createOscillator();
      final level = context.createGain();
      oscillator.type = wave;
      oscillator.frequency.value = accent ? accentFreq : freq;
      level.gain.setValueAtTime(peak, now);
      level.gain.exponentialRampToValueAtTime(0.001, now + decay);
      oscillator.connect(level);
      level.connect(context.destination);
      oscillator.start(now);
      oscillator.stop(now + decay + 0.01);
    } catch (error) {
      onError?.call(error);
    }
  }

  @override
  Future<void> dispose() async {
    if (_disposed) return;
    _disposed = true;
    final context = _context;
    _context = null;
    if (context == null) return;
    try {
      await context.close().toDart;
    } catch (_) {
      // Already closed; nothing to do.
    }
  }
}
